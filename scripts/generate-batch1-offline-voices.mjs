import { mkdir, open, rename, rm, stat, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { CURRICULUM_VOICE_CORPUS, getMissingCurriculumVoiceAssets } from '../src/data/curriculumVoice.js';
import { LETTER_LAUNCH_PROMPT_CORPUS } from '../src/data/letterLaunch.js';
import { STORYBOOK_LEARNING_VOICE_CORPUS } from '../src/data/storybookLearning.js';
import { BATCH2_VOICE_CORPUS_BY_GAME } from '../src/data/batch2Narration.js';
import { OFFLINE_VOICE_MANIFEST as sourceManifest } from '../src/data/offlineVoiceManifest.js';
import { voiceClipKey } from '../src/data/voiceKey.js';

const root = resolve(import.meta.dirname, '..');
const origin = 'https://dinospace-eight.vercel.app';
const endpoint = `${origin}/api/voice`;
const requestStatePath = resolve(root, 'tmp/offline-voice-request-state.json');
const lockPath = resolve(root, 'tmp/offline-voice-generator.lock');
const requestWindowMs = 10 * 60 * 1000;
const requestLimit = 30;
const requestedMaxCalls = Number(process.argv.find((arg) => arg.startsWith('--max-calls='))?.slice('--max-calls='.length) || 20);
if (!Number.isInteger(requestedMaxCalls) || requestedMaxCalls < 1 || requestedMaxCalls > 20) throw new Error('--max-calls must be an integer from 1 to 20.');
const storybookOnly = process.argv.includes('--storybook-only');
const batch2Only = process.argv.includes('--batch2-only');
const manifestPath = resolve(root, 'src/data/offlineVoiceManifest.js');
const manifest = new Map(Object.entries(sourceManifest));
const extraRetryLines = [
  'Use the outlines and position of each land shape on the world map. Which one is the clue asking for?',
  'Look at where the ocean sits around the continents, then try again.',
  'A country is a place inside a continent. Look at where it sits on the world map, then try again.',
];

const voiceItem = (text, path = `/audio/en/${voiceClipKey(text, 'en-US')}-matilda.mp3`) => ({
  text,
  key: voiceClipKey(text, 'en-US'),
  path,
});
const corpora = {
  batch2PuzzlePop: BATCH2_VOICE_CORPUS_BY_GAME.puzzlePop.map((text) => voiceItem(text)),
  batch2SpotDifference: BATCH2_VOICE_CORPUS_BY_GAME.spotDifference.map((text) => voiceItem(text)),
  batch2SkyShapes: BATCH2_VOICE_CORPUS_BY_GAME.skyShapes.map((text) => voiceItem(text)),
  batch2MonsterMath: BATCH2_VOICE_CORPUS_BY_GAME.monsterMath.map((text) => voiceItem(text)),
  storybook: STORYBOOK_LEARNING_VOICE_CORPUS.map(({ text, key }) => ({ text, key, path: `/audio/en/${key}-matilda.mp3` })),
  letterLaunch: LETTER_LAUNCH_PROMPT_CORPUS.map((text) => voiceItem(text)),
  curriculum: CURRICULUM_VOICE_CORPUS.map(({ text, key }) => ({ text, key, path: `/audio/en/${key}-matilda.mp3` })),
  retries: extraRetryLines.map((text) => voiceItem(text)),
};
for (const item of getMissingCurriculumVoiceAssets()) corpora.curriculum.push({ text: item.text, key: item.key, path: item.path });
if (storybookOnly && batch2Only) throw new Error('Choose at most one corpus selector.');
const selectedCorpora = batch2Only ? {
  batch2PuzzlePop: corpora.batch2PuzzlePop,
  batch2SpotDifference: corpora.batch2SpotDifference,
  batch2SkyShapes: corpora.batch2SkyShapes,
  batch2MonsterMath: corpora.batch2MonsterMath,
} : storybookOnly ? { storybook: corpora.storybook } : {
  storybook: corpora.storybook,
  letterLaunch: corpora.letterLaunch,
  curriculum: corpora.curriculum,
  retries: corpora.retries,
};
const requested = new Map(Object.values(selectedCorpora).flat().map((item) => [item.key, item]));

const absolutePath = (publicPath) => resolve(root, 'public', publicPath.replace(/^\//, ''));
const isReady = async (publicPath) => {
  try { return (await stat(absolutePath(publicPath))).size > 1000; } catch { return false; }
};
const persistManifest = async () => {
  const ordered = Object.fromEntries([...manifest.entries()].sort(([left], [right]) => left.localeCompare(right)));
  const temporaryPath = `${manifestPath}.tmp`;
  await writeFile(temporaryPath, `// Generated by scripts/generate-offline-voices.mjs and scripts/generate-batch1-offline-voices.mjs.\nexport const OFFLINE_VOICE_MANIFEST = ${JSON.stringify(ordered, null, 2)};\n`);
  await rename(temporaryPath, manifestPath);
};

await mkdir(resolve(root, 'public/audio/en'), { recursive: true });
const checkReady = process.argv.includes('--check-ready');
const dryRun = process.argv.includes('--dry-run') || checkReady;
if (dryRun) {
  let ready = 0;
  const breakdown = {};
  const counted = new Set();
  for (const [name, items] of Object.entries(selectedCorpora)) {
    let groupReady = 0;
    let groupPending = 0;
    for (const item of items) {
      if (counted.has(item.key)) continue;
      counted.add(item.key);
      const candidates = [...new Set([manifest.get(item.key), item.path].filter(Boolean))];
      let exists = false;
      for (const candidate of candidates) if (await isReady(candidate)) { exists = true; break; }
      if (exists) { ready += 1; groupReady += 1; } else groupPending += 1;
    }
    breakdown[name] = { ready: groupReady, pending: groupPending };
  }
  console.log(JSON.stringify({ requested: requested.size, ready, pending: requested.size - ready, breakdown, maxCalls: requestedMaxCalls, storybookOnly, batch2Only, dryRun: true }));
  process.exit(checkReady && ready < requested.size ? 1 : 0);
}

await mkdir(resolve(root, 'tmp'), { recursive: true });
let lock;
try {
  lock = await open(lockPath, 'wx');
} catch (error) {
  if (error.code === 'EEXIST') throw new Error(`A voice generation lock exists at ${lockPath}; inspect its recorded PID before removing a stale lock.`);
  throw error;
}
await lock.writeFile(`${JSON.stringify({ pid: process.pid, startedAt: new Date().toISOString() })}\n`);
const loadRequestState = async () => {
  try {
    const state = JSON.parse(await readFile(requestStatePath, 'utf8'));
    const now = Date.now();
    return {
      requests: Array.isArray(state.requests) ? state.requests.filter((item) => Number.isFinite(item.at) && now - item.at < requestWindowMs) : [],
      blockedUntil: Number.isFinite(state.blockedUntil) ? state.blockedUntil : 0,
    };
  } catch {
    return { requests: [], blockedUntil: 0 };
  }
};
let requestState;
let runBudget = 0;
try {
  requestState = await loadRequestState();
  if (requestState.blockedUntil > Date.now()) throw new Error(`Voice API cooldown is active until ${new Date(requestState.blockedUntil).toISOString()}.`);
  runBudget = Math.min(requestedMaxCalls, requestLimit - requestState.requests.length);
  if (runBudget < 1) throw new Error('The voice request journal shows no safe calls left in this ten-minute window. Resume after it expires.');
} catch (error) {
  await lock.close();
  await rm(lockPath, { force: true });
  throw error;
}

let generated = 0;
let reused = 0;
let stoppedAt = '';
try {
for (const item of requested.values()) {
  if (generated >= runBudget) break;
  const priorPath = manifest.get(item.key);
  if (priorPath && await isReady(priorPath)) { reused += 1; continue; }
  const candidates = [...new Set([priorPath, item.path].filter(Boolean))];
  let reusablePath = '';
  for (const candidate of candidates) {
    if (await isReady(candidate)) { reusablePath = candidate; break; }
  }
  if (reusablePath) {
    manifest.set(item.key, reusablePath);
    await persistManifest();
    reused += 1;
    continue;
  }

  await mkdir(dirname(absolutePath(item.path)), { recursive: true });
  requestState.requests.push({ at: Date.now() });
  await writeFile(`${requestStatePath}.tmp`, `${JSON.stringify(requestState, null, 2)}\n`);
  await rename(`${requestStatePath}.tmp`, requestStatePath);
  const response = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Origin: origin },
    body: JSON.stringify({ text: item.text, language: 'en' }),
  });
  if (response.status === 204 || response.status === 429) {
    stoppedAt = `${response.status}`;
    requestState.blockedUntil = Date.now() + requestWindowMs;
    await writeFile(`${requestStatePath}.tmp`, `${JSON.stringify(requestState, null, 2)}\n`);
    await rename(`${requestStatePath}.tmp`, requestStatePath);
    console.error(`Stopped on a voice endpoint response of ${response.status}. No retry attempted.`);
    break;
  }
  if (!response.ok) {
    stoppedAt = `${response.status}`;
    console.error(`Stopped on voice endpoint status ${response.status}. No retry attempted.`);
    break;
  }
  if (response.headers.get('x-amari-voice-provider') !== 'elevenlabs') {
    stoppedAt = 'provider-unverified';
    console.error('Stopped because the voice provider could not be verified. Response was not saved.');
    break;
  }
  const mimeType = (response.headers.get('content-type') || '').split(';')[0].trim().toLowerCase();
  if (mimeType !== 'audio/mpeg') {
    stoppedAt = 'mime-unverified';
    console.error(`Stopped because the response MIME type was ${mimeType || 'missing'}, not audio/mpeg. Response was not saved.`);
    break;
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 1000) {
    stoppedAt = 'response-too-small';
    console.error(`Stopped because the audio response was only ${bytes.length} bytes. Response was not saved.`);
    break;
  }
  const output = absolutePath(item.path);
  const temporaryOutput = `${output}.tmp`;
  await writeFile(temporaryOutput, bytes);
  await rename(temporaryOutput, output);
  manifest.set(item.key, item.path);
  await persistManifest();
  generated += 1;
}

const pending = [];
for (const item of requested.values()) {
  const publicPath = manifest.get(item.key) || item.path;
  if (!await isReady(publicPath)) pending.push(item.key);
}
console.log(JSON.stringify({ requested: requested.size, generated, reused, pending: pending.length, maxCalls: runBudget, storybookOnly, batch2Only, stoppedAt: stoppedAt || null }));
if (stoppedAt) process.exitCode = stoppedAt === '429' ? 75 : 1;
} finally {
  await lock.close();
  await rm(lockPath, { force: true });
}
